const DICT = { ar, en };

export function t(lang, key, params = {}) {
  const v = DICT[normLang(lang)][key] ?? ar[key];
  if (v === undefined) return key;
  return typeof v === 'function' ? v(params) : v;
}

export function list(lang, arr, n = 5) {
  const shown = arr.slice(0, n).join(t(lang, 'list.sep'));
  return arr.length > n ? shown + t(lang, 'list.more', { n: arr.length - n }) : shown;
}
